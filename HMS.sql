-- CREATE VIEWS (Separate each CREATE VIEW into a new batch with GO)
GO

CREATE VIEW DOCTOR_VIEW AS
SELECT E.EMPLOYEE_NAME, E.EMPLOYEE_DEPARTMENT, E.EMPLOYEE_DESIGNATION, Q.QUALIFICATION, E.ROOM_ID
FROM EMPLOYEE E
JOIN EMPLOYEE_QUALIFICATION Q ON E.EMPLOYEE_ID = Q.EMPLOYEE_ID
WHERE E.EMPLOYEE_NAME LIKE 'Dr%';

GO

CREATE VIEW PATIENT_VIEW AS
SELECT P.PATIENT_ID, P.PATIENT_NAME, P.PATIENT_AGE, P.GENDER, C.PATIENT_CONTACT_NUMBER
FROM PATIENT P
JOIN PATIENT_CONTACT C ON P.PATIENT_ID = C.PATIENT_ID;

GO

CREATE VIEW EMPLOYEE_VIEW AS
SELECT E.EMPLOYEE_NAME, E.EMPLOYEE_DEPARTMENT, E.EMPLOYEE_DESIGNATION, Q.QUALIFICATION, C.EMPLOYEE_CONTACT_NUMBER, E.ROOM_ID
FROM EMPLOYEE E
JOIN EMPLOYEE_CONTACT C ON E.EMPLOYEE_ID = C.EMPLOYEE_ID
JOIN EMPLOYEE_QUALIFICATION Q ON E.EMPLOYEE_ID = Q.EMPLOYEE_ID;

GO

CREATE VIEW PATIENT_APPOINTMENT AS
SELECT A.PATIENT_ID, A.APPOINTMENT_DATE, D.DISEASE, P.MEDICINE_NAME, P.DOSAGE, P.DURATION
FROM APPOINTMENT A
JOIN APPOINTMENT_DISEASE D ON A.APPOINTMENT_ID = D.APPOINTMENT_ID
JOIN APPOINTMENT_PERSCRIPTION P ON A.APPOINTMENT_ID = P.APPOINTMENT_ID;

GO

CREATE VIEW NURSE_PATIENT AS
SELECT A.PATIENT_ID, AD.ADMISSION_DATE, D.DISEASE, P.MEDICINE_NAME, P.DOSAGE, P.DURATION
FROM APPOINTMENT A
JOIN APPOINTMENT_DISEASE D ON A.APPOINTMENT_ID = D.APPOINTMENT_ID
JOIN APPOINTMENT_PERSCRIPTION P ON A.APPOINTMENT_ID = P.APPOINTMENT_ID
JOIN ADMISSION AD ON A.APPOINTMENT_ID = AD.APPOINTMENT_ID;

GO

-- CREATE ROLES AND PRIVILEGES (This part stays as is)
CREATE ROLE PATIENT_ROLE;
GRANT SELECT, INSERT, UPDATE (PATIENT_NAME, PATIENT_AGE, GENDER, PATIENT_CONTACT_NUMBER) ON PATIENT_VIEW TO PATIENT_ROLE;
GRANT SELECT ON TEST TO PATIENT_ROLE;
GRANT SELECT ON DOCTOR_VIEW TO PATIENT_ROLE;

GO

CREATE ROLE RECEPTIONIST;
GRANT INSERT, SELECT, UPDATE ON PATIENT TO RECEPTIONIST;
GRANT SELECT ON EMPLOYEE_VIEW TO RECEPTIONIST;
GRANT SELECT ON ROOMS TO RECEPTIONIST;
GRANT SELECT, INSERT, UPDATE, DELETE ON APPOINTMENT TO RECEPTIONIST;
GRANT SELECT ON TEST TO RECEPTIONIST;
GRANT INSERT, SELECT, UPDATE ON ADMISSION TO RECEPTIONIST;
GRANT INSERT, SELECT, UPDATE ON INVOICE TO RECEPTIONIST;

GO

CREATE ROLE DOCTOR;
GRANT SELECT, INSERT, UPDATE ON PATIENT_APPOINTMENT TO DOCTOR;

GO

CREATE ROLE NURSE;
GRANT SELECT ON NURSE_PATIENT TO NURSE;

GO

CREATE ROLE LAB_TECHNICIAN;
GRANT SELECT, INSERT, UPDATE ON PATIENT_TESTS TO LAB_TECHNICIAN;
GRANT SELECT ON TEST TO LAB_TECHNICIAN;

GO


