    CONSTRAINT ADMISSION_FK1 FOREIGN KEY (APPOINTMENT_ID) REFERENCES APPOINTMENT(APPOINTMENT_ID),
    CONSTRAINT ADMISSION_FK2 FOREIGN KEY (ROOM_ID) REFERENCES ROOMS(ROOM_ID)
);

CREATE TABLE ADMITTED_PATIENT
(
    PATIENT_ID VARCHAR(25) NOT NULL,
    ADMISSION_ID INT NOT NULL,
    CONSTRAINT ADMITTED_PATIENT_PK PRIMARY KEY (PATIENT_ID, ADMISSION_ID),
    CONSTRAINT ADMITTED_PATIENT_FK1 FOREIGN KEY (PATIENT_ID) REFERENCES PATIENT(PATIENT_ID),
    CONSTRAINT ADMITTED_PATIENT_FK2 FOREIGN KEY (ADMISSION_ID) REFERENCES ADMISSION(ADMISSION_ID)
