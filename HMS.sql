-- CREATE TABLES
CREATE TABLE ROOMS
(
    ROOM_ID INT NOT NULL,
    ROOM_TYPE VARCHAR(15),
    COUNT_OF_PERSONS INT,
    ROOM_CAPACITY INT,
    ROOM_AVAILABILITY VARCHAR(3) CHECK(ROOM_AVAILABILITY IN ('YES', 'NO')),
    CONSTRAINT ROOMS_PK PRIMARY KEY (ROOM_ID)
);

CREATE TABLE TEST
(
    TEST_ID INT NOT NULL,
    TEST_NAME VARCHAR(25),
    TEST_COST DECIMAL(6,2),
    CONSTRAINT TEST_PK PRIMARY KEY (TEST_ID)
);

CREATE TABLE EMPLOYEE
(
    EMPLOYEE_ID VARCHAR(25) NOT NULL,
    EMPLOYEE_NAME VARCHAR(25),
    EMPLOYEE_DEPARTMENT VARCHAR(40),
    EMPLOYEE_DESIGNATION VARCHAR(25),
    ROOM_ID INT,
    CONSTRAINT EMPLOYEE_PK PRIMARY KEY (EMPLOYEE_ID),
    CONSTRAINT EMPLOYEE_FK FOREIGN KEY (ROOM_ID) REFERENCES ROOMS(ROOM_ID)
);

CREATE TABLE EMPLOYEE_CONTACT
(
    EMPLOYEE_ID VARCHAR(25) NOT NULL,
    EMPLOYEE_CONTACT_NUMBER VARCHAR(15) NOT NULL,
    CONSTRAINT EMPLOYEE_CONTACT_PK PRIMARY KEY (EMPLOYEE_ID, EMPLOYEE_CONTACT_NUMBER),
    CONSTRAINT EMPLOYEE_CONTACT_FK FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEE(EMPLOYEE_ID)
);

CREATE TABLE EMPLOYEE_QUALIFICATION
(
    EMPLOYEE_ID VARCHAR(25) NOT NULL,
    QUALIFICATION VARCHAR(40) NOT NULL,
    CONSTRAINT EMPLOYEE_QUALIFICATION_PK PRIMARY KEY (EMPLOYEE_ID, QUALIFICATION),
    CONSTRAINT EMPLOYEE_QUALIFICATION_FK FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEE(EMPLOYEE_ID)
);

CREATE TABLE PATIENT
(
    PATIENT_ID VARCHAR(25) NOT NULL,
    PATIENT_NAME VARCHAR(25),
    PATIENT_AGE INT,
    GENDER VARCHAR(1) CHECK(GENDER IN ('M', 'F')),
    CONSTRAINT PATIENT_PK PRIMARY KEY (PATIENT_ID)
);

CREATE TABLE PATIENT_CONTACT
(
    PATIENT_ID VARCHAR(25) NOT NULL,
    PATIENT_CONTACT_NUMBER VARCHAR(15) NOT NULL,
    CONSTRAINT PATIENT_CONTACT_PK PRIMARY KEY (PATIENT_ID, PATIENT_CONTACT_NUMBER),
    CONSTRAINT PATIENT_CONTACT_FK FOREIGN KEY (PATIENT_ID) REFERENCES PATIENT(PATIENT_ID)
);

CREATE TABLE APPOINTMENT
(
    APPOINTMENT_ID INT NOT NULL,
    EMPLOYEE_ID VARCHAR(25),
    PATIENT_ID VARCHAR(25),
    APPOINTMENT_DATE DATETIME DEFAULT GETDATE(),
    CONSTRAINT APPOINTMENT_PK PRIMARY KEY (APPOINTMENT_ID),
    CONSTRAINT APPOINTMENT_FK1 FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEE(EMPLOYEE_ID),
    CONSTRAINT APPOINTMENT_FK2 FOREIGN KEY (PATIENT_ID) REFERENCES PATIENT(PATIENT_ID)
);

CREATE TABLE APPOINTMENT_DISEASE
(
    APPOINTMENT_ID INT NOT NULL,
    DISEASE VARCHAR(25) NOT NULL,
    CONSTRAINT APPOINTMENT_DISEASE_PK PRIMARY KEY (APPOINTMENT_ID, DISEASE),
    CONSTRAINT APPOINTMENT_DISEASE_FK FOREIGN KEY (APPOINTMENT_ID) REFERENCES APPOINTMENT(APPOINTMENT_ID)
);

CREATE TABLE APPOINTMENT_PERSCRIPTION
(
    APPOINTMENT_ID INT NOT NULL,
    MEDICINE_NAME VARCHAR(25) NOT NULL,
    DOSAGE VARCHAR(40),
    DURATION VARCHAR(25),
    CONSTRAINT APPOINTMENT_PERSCRIPTION_PK PRIMARY KEY (APPOINTMENT_ID, MEDICINE_NAME),
    CONSTRAINT APPOINTMENT_PERSCRIPTION_FK FOREIGN KEY (APPOINTMENT_ID) REFERENCES APPOINTMENT(APPOINTMENT_ID)
);

CREATE TABLE ADMISSION
(
    ADMISSION_ID INT NOT NULL,
    APPOINTMENT_ID INT,
    ROOM_ID INT,
    ADMISSION_DATE DATETIME DEFAULT GETDATE(),
    DISCHARGE_DATE DATETIME,
